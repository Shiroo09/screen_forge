//! Live upload to Litterbox. Ignored by default (network + third-party service);
//! run with `cargo test -p sf-net --test upload_live -- --ignored`.

#[test]
#[ignore = "hits the live Litterbox service; returns 403 from IPs it rate-limits/geo-blocks (verified with curl too)"]
#[allow(dead_code)]
fn uploads_a_small_png_and_returns_a_url() {
    // A 1x1 PNG, the smallest valid image.
    const PNG_1X1: &[u8] = &[
        0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44,
        0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00, 0x00, 0x1F,
        0x15, 0xC4, 0x89, 0x00, 0x00, 0x00, 0x0A, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9C, 0x63, 0x00,
        0x01, 0x00, 0x00, 0x05, 0x00, 0x01, 0x0D, 0x0A, 0x2D, 0xB4, 0x00, 0x00, 0x00, 0x00, 0x49,
        0x45, 0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82,
    ];

    let url = sf_net::http_upload::upload(PNG_1X1, "image/png", Some("sf-test.png"))
        .expect("upload should succeed");

    println!("uploaded: {url}");
    assert!(url.starts_with("http"), "expected a URL, got {url}");
    assert!(url.contains("catbox") || url.contains("litter"), "unexpected host: {url}");
}
